"""Exact channel-specific FER oracles for declared packed-ququart channels."""

from __future__ import annotations

from decimal import Decimal, localcontext
from functools import lru_cache
from itertools import product
from typing import Iterable, Sequence

from qec.decoder.ququart.codes import packed_five_ququart_code
from qec.decoder.ququart.exact import ExactDecoder
from qec.decoder.ququart.packed import identity, local_pauli
from qec.sonify.canonical import canonical_sha256

from .channels import CHANNELS, classify_error
from .oracle import DEFAULT_ERROR_RATES, exact_weight_enumerator

EXACT_CHANNEL_SCHEMA = "qec.ququart-exact-channel-oracle.v1"
LANE_SYMMETRY_SCHEMA = "qec.ququart-lane-symmetry.v1"


def _binomial(n: int, k: int) -> int:
    if k < 0 or k > n:
        return 0
    result = 1
    for value in range(1, min(k, n - k) + 1):
        result = result * (n - value + 1) // value
    return result


def _power(base: Decimal, exponent: int) -> Decimal:
    if exponent < 0:
        raise ValueError("exponent must be non-negative")
    result = Decimal(1)
    for _ in range(exponent):
        result *= base
    return result


def _rate(value: Decimal) -> str:
    if value.is_zero():
        return "0"
    return format(value, ".18E")


def _project_row(row: dict[str, int | str]) -> tuple[int, ...]:
    return (
        int(row["weight"]),
        int(row["patterns"]),
        int(row["corrected"]),
        int(row["detected_uncorrectable"]),
        int(row["logical_failure"]),
        int(row["frame_failures"]),
    )


@lru_cache(maxsize=None)
def exact_channel_weight_enumerator(
    channel: str,
) -> tuple[dict[str, int | str], ...]:
    """Enumerate every pattern generated by one declared local channel.

    The full packed-depolarizing channel reuses the optimized 16**5 oracle.
    Restricted three-operator channels contain only 4**5 patterns and are
    enumerated directly through the production decoder.
    """

    try:
        local_errors = CHANNELS[channel]
    except KeyError as error:
        raise ValueError(f"unknown ququart channel: {channel}") from error

    code = packed_five_ququart_code()
    local_count = len(local_errors)
    if channel == "full_packed_depolarizing":
        return tuple(
            {
                "channel": channel,
                "local_nonidentity_operators": local_count,
                **row,
            }
            for row in exact_weight_enumerator()
        )

    decoder = ExactDecoder(code, max_weight=1)
    counts = {
        weight: {
            "corrected": 0,
            "detected_uncorrectable": 0,
            "logical_failure": 0,
        }
        for weight in range(code.n + 1)
    }
    site_errors = tuple(
        tuple(
            local_pauli(code.n, site, lane0, lane1)
            for lane0, lane1 in local_errors
        )
        for site in range(code.n)
    )

    # 0 denotes identity; 1..m select one declared local nonidentity operator.
    for word in product(range(local_count + 1), repeat=code.n):
        error = identity(code.n)
        for site, choice in enumerate(word):
            if choice:
                error = error.compose(site_errors[site][choice - 1])
        counts[error.weight][classify_error(decoder, error)] += 1

    rows: list[dict[str, int | str]] = []
    for weight in range(code.n + 1):
        values = counts[weight]
        patterns = sum(values.values())
        expected = _binomial(code.n, weight) * (local_count ** weight)
        if patterns != expected:
            raise AssertionError(
                f"{channel} weight-{weight} enumerator mismatch: "
                f"{patterns} != {expected}"
            )
        rows.append({
            "channel": channel,
            "local_nonidentity_operators": local_count,
            "weight": weight,
            "patterns": patterns,
            "corrected": values["corrected"],
            "detected_uncorrectable": values["detected_uncorrectable"],
            "logical_failure": values["logical_failure"],
            "frame_failures": (
                values["detected_uncorrectable"] + values["logical_failure"]
            ),
        })

    expected_total = (local_count + 1) ** code.n
    if sum(int(row["patterns"]) for row in rows) != expected_total:
        raise AssertionError(f"{channel} did not enumerate its full local alphabet")
    return tuple(rows)


def exact_channel_fer_row(
    channel: str,
    error_rate: str | Decimal,
) -> dict[str, str | int]:
    """Evaluate exact finite FER for one iid declared local channel."""

    p = Decimal(error_rate)
    if p < 0 or p > 1:
        raise ValueError("physical error rate must be in [0, 1]")
    enumerator = exact_channel_weight_enumerator(channel)
    weights = tuple(int(row["weight"]) for row in enumerator)
    n = max(weights)
    if weights != tuple(range(n + 1)):
        raise AssertionError("channel enumerator must cover every weight from 0 through n")
    local_count = int(enumerator[0]["local_nonidentity_operators"])

    with localcontext() as context:
        context.prec = 60
        local = p / Decimal(local_count)
        identity_probability = Decimal(1) - p
        corrected = Decimal(0)
        detected = Decimal(0)
        logical = Decimal(0)
        for row in enumerator:
            weight = int(row["weight"])
            probability_per_pattern = (
                _power(local, weight)
                * _power(identity_probability, n - weight)
            )
            corrected += Decimal(int(row["corrected"])) * probability_per_pattern
            detected += (
                Decimal(int(row["detected_uncorrectable"]))
                * probability_per_pattern
            )
            logical += (
                Decimal(int(row["logical_failure"]))
                * probability_per_pattern
            )

        failure = detected + logical
        total = corrected + failure
        if abs(total - Decimal(1)) > Decimal("1e-45"):
            raise AssertionError(f"{channel} probabilities do not sum to one: {total}")
        return {
            "channel": channel,
            "local_nonidentity_operators": local_count,
            "physical_error_rate": str(p),
            "frame_error_rate": _rate(failure),
            "success_rate": _rate(corrected),
            "detected_uncorrectable_rate": _rate(detected),
            "logical_failure_rate": _rate(logical),
        }


def exact_channel_fer_curve(
    error_rates: Iterable[str] = DEFAULT_ERROR_RATES,
    *,
    channels: Sequence[str] = tuple(CHANNELS),
) -> tuple[dict[str, str | int], ...]:
    rates = tuple(error_rates)
    return tuple(
        exact_channel_fer_row(channel, rate)
        for channel in channels
        for rate in rates
    )


def lane_symmetry_certificate() -> dict[str, object]:
    """Certify equality of the two restricted encoded-qubit lane channels."""

    lane0 = tuple(
        _project_row(row)
        for row in exact_channel_weight_enumerator("lane0_only")
    )
    lane1 = tuple(
        _project_row(row)
        for row in exact_channel_weight_enumerator("lane1_only")
    )
    payload: dict[str, object] = {
        "schema": LANE_SYMMETRY_SCHEMA,
        "channels": ["lane0_only", "lane1_only"],
        "weight_enumerators_equal": lane0 == lane1,
        "rows_compared": len(lane0),
        "claim": (
            "The packed construction is exactly symmetric under exchange of "
            "the two encoded-qubit lanes for the declared single-lane channels."
        ),
    }
    payload["sha256"] = canonical_sha256(payload)
    if not payload["weight_enumerators_equal"]:
        raise AssertionError("lane-0 and lane-1 exact enumerators differ")
    return payload
